const fs = require('fs');
const path = require('path');
const stylePath = path.join(__dirname, '..', 'app', 'style.css');
let css = fs.readFileSync(stylePath, 'utf8');
const marker = 'body.provider-mode #v-legal-agb-onboarding.phase7-applite .panel{';
const idx = css.indexOf(marker);
if (idx === -1) throw new Error('phase7 marker not found');
const endBlock = css.indexOf('\n}', idx);
const cut = css.slice(0, endBlock + 2).trimEnd();
const junk = css.length - cut.length;
fs.writeFileSync(stylePath, cut + '\n');
console.log('Removed', junk, 'bytes of duplicate/junk CSS');
